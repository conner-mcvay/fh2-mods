<#
.SYNOPSIS
  Regenerates imports.txt and index-donors.txt for stock-wheel-swap from a stock FH2 game folder.

.DESCRIPTION
  The wheel shop loads every non-stock wheel from cars\_library\scene\wheels\<MediaName>.zip
  (<MediaName>_wheelLF.modelbin + Textures\AO\<MediaName>_wheelLF_AO.swatchbin). Stock wheels only exist inside
  their car's zip, so each converted wheel gets its own wheel zip, built at install time from the player's game
  files. Run this after changing the wheel list in the SQL patch.

.EXAMPLE
  .\mods\stock-wheel-swap\Generate-Imports.ps1 -Game "G:\FH2-1\Anthem_1.0.0.64_x64__8wekyb3d8bbwe" -Sqlite G:\FH2-1\tools\sqlite3.exe
#>
param([Parameter(Mandatory)][string]$Game, [string]$Sqlite = 'sqlite3')
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.IO.Compression.FileSystem
$media = Join-Path $Game 'Mount\media'
$sql = Get-Content (Join-Path $PSScriptRoot 'media\stripped\gamedbRC.slt\stock-wheel-swap.sql') -Raw -Encoding UTF8
$wheels = [regex]::Matches($sql, "(?m)^  \('([^']+)', '") | ForEach-Object { $_.Groups[1].Value }

# the car zip each wheel comes from: the car of the same name, else a car that has it as its stock wheel
$db = (Join-Path $media 'stripped\gamedbRC.slt').Replace('\', '/')
$src = @{}
& $Sqlite -separator '|' "file:$db`?immutable=1" @"
SELECT w.MediaName, COALESCE((SELECT c.MediaName FROM Data_Car c WHERE c.MediaName = w.MediaName COLLATE NOCASE),
                             (SELECT c.MediaName FROM Data_Car c WHERE c.StockWheelID = w.ID ORDER BY c.Id LIMIT 1))
FROM List_Wheels w
"@ | ForEach-Object { $w, $c = $_.Split('|'); if ($c) { $src[$w.ToLower()] = $c } }

$imports = @('# generated by Generate-Imports.ps1: one wheel zip per converted stock wheel, from its car''s zip')
$donors = @('# new wheel zips reuse the index metadata of a stock aftermarket wheel zip')
$missing = @()
foreach ($w in $wheels) {
  $car = $src[$w.ToLower()]
  $zipPath = Get-ChildItem (Join-Path $media 'cars') -Filter "$car.zip" | Select-Object -First 1
  if (-not $zipPath) { $missing += "$w (no car zip $car)"; continue }
  $z = [IO.Compression.ZipFile]::OpenRead($zipPath.FullName)
  try {
    # names vary (_wheelLF, _wheel_LF, only LR for staggered sets, 918_Spyder vs 918Spyder, a variant car's own
    # name): take the car's wheel model, front-left first, one named like the wheel first
    $norm = ($w -replace '_', '').ToLower()
    $rank = { param($n) $s = 0; if (($n -replace '_', '').ToLower() -like "*$norm*") { $s -= 10 }; if ($n -match '(?i)wheel_?LF') { $s -= 2 } elseif ($n -match '(?i)wheel_?LR') { $s -= 1 }; $s }
    $model = $z.Entries | Where-Object { $_.FullName -match '(?i)/Wheels?/[^/]+\.modelbin$' } | Sort-Object { & $rank $_.Name } | Select-Object -First 1
    $side = if ($model -and $model.Name -match '(?i)wheel_?LR') { 'LR' } else { 'LF' }
    $ao = $z.Entries | Where-Object { $_.FullName -match "(?i)^Textures/AO/[^/]*wheel_?$side`_AO\.swatchbin$" } | Sort-Object { & $rank $_.Name } | Select-Object -First 1
  } finally { $z.Dispose() }
  if (-not $model) { $missing += "$w (no wheel model in $car.zip)"; continue }
  $dest = "cars\_library\scene\wheels\$w.zip"
  $from = "fh2:cars\$($zipPath.Name)"
  $imports += "$dest\$($w)_wheelLF.modelbin <- $from\$($model.FullName.Replace('/', '\'))"
  if ($ao) { $imports += "$dest\Textures\AO\$($w)_wheelLF_AO.swatchbin <- $from\$($ao.FullName.Replace('/', '\'))" }
  $donors += "$dest <- cars\_library\scene\wheels\VOL_TE37.zip"
}
Set-Content (Join-Path $PSScriptRoot 'imports.txt') $imports -Encoding ASCII
Set-Content (Join-Path $PSScriptRoot 'index-donors.txt') $donors -Encoding ASCII
"$($donors.Count - 1) wheel zips; $($imports.Count - $donors.Count) AO textures included"
if ($missing) { Write-Warning ("Skipped:`n  " + ($missing -join "`n  ")) }
