-- stock-wheel-swap: every car's stock wheels become wheel options for any car.
-- For each stock wheel the game has a model for (named after an FH2 car, or some FH2 car's stock wheel):
--   IsStock 0             listed in the wheel shop like aftermarket wheels
--   PartManufacturerID    the car brand's List_PartManufacturer row (TOY -> Toyota, POR -> Porsche, ...);
--                         the MediaName prefix picks it, the same make codes List_CarMake uses
--   DisplayName           model year + the game's own English name of the car it comes from
--   Price                 by weight, on the aftermarket wheels' scale (30 kg 3700 ... 39.5 kg 3400 CR)
-- Traffic (PG_Bus, PG_BoxTruck) and placeholder (NUL_Car_00) wheels stay stock. So do 169 leftover rows from
-- older games whose car isn't in FH2: their models aren't in the game.

